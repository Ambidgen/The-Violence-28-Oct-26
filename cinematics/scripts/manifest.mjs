// Write the short-cutscene manifest for the engine, and the docs table, from the registry.
//
//   node scripts/manifest.mjs
//
// Outputs
//   cinematics/shorts.json                  what the pipeline renders
//   assets/cutscenes/shorts/shorts.json     the copy the game reads at runtime
//   cinematics/SHORTS.md                    the table in the README's voice
//
// The video files the game plays are made by scripts/to_game-shorts.sh.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {SHORTS, FPS} from '../src/shorts/registry.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const gameDir = path.resolve(root, '..', 'assets', 'cutscenes', 'shorts');

const manifest = {
  generator: 'cinematics/scripts/manifest.mjs',
  note: 'Short in-game cutscenes (5-10 s). Rendered by Remotion from cinematics/. The game plays the Ogg Theora files and may draw its own text in the slots.',
  fps: FPS,
  master: {width: 1920, height: 1080},
  video: {dir: 'res://assets/cutscenes/shorts', ext: 'ogv', width: 1280, height: 720},
  shorts: SHORTS.map((s) => ({
    id: s.id,
    key: s.key,
    file: s.file.replace(/\.jsx$/, ''),
    title: s.title,
    blurb: s.blurb,
    trigger: s.trigger,
    poster: s.poster,
    tags: s.tags,
    frames: s.frames,
    seconds: Number((s.frames / FPS).toFixed(3)),
    slots: s.slots,
    props: s.defaultProps,
    propDocs: s.props,
    sound: s.sound,
  })),
};

fs.writeFileSync(path.join(root, 'shorts.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.mkdirSync(gameDir, {recursive: true});
fs.writeFileSync(path.join(gameDir, 'shorts.json'), JSON.stringify(manifest, null, 2) + '\n');

// ---------------------------------------------------------------- the docs table
const lines = [];
lines.push('# The short cutscenes');
lines.push('');
lines.push('Generated by `node scripts/manifest.mjs` from `src/shorts/registry.js`. Do not edit by hand.');
lines.push('');
lines.push('Every short runs 5-10 s at 30 fps, 1920x1080, and is drawn from the same page as the opening');
lines.push('(paper, ink, stepped greys, one red that only marks where the plan touched a real room).');
lines.push('Each one is prop-driven: the plates are drawn, the words come from the campaign. Where a');
lines.push('`slots` entry is listed, the engine may also paint its own text over an empty plate instead');
lines.push('of asking for a re-render.');
lines.push('');
lines.push('| # | id | Scene | Length | Fires on |');
lines.push('|---|----|-------|--------|----------|');
SHORTS.forEach((s, i) => {
  lines.push(`| ${i + 1} | \`${s.id}\` | ${s.title} | ${(s.frames / FPS).toFixed(1)} s | ${s.trigger} |`);
});
lines.push('');
for (const s of SHORTS) {
  lines.push(`## ${s.id} · ${s.title}`);
  lines.push('');
  lines.push(`${s.blurb}`);
  lines.push('');
  lines.push(`- **Length:** ${s.frames} frames, ${(s.frames / FPS).toFixed(3)} s`);
  lines.push(`- **Fires on:** ${s.trigger}`);
  lines.push(`- **Source:** \`src/shorts/${s.file}\``);
  lines.push(`- **Sound:** ${s.sound.join(', ')}`);
  lines.push('');
  lines.push('| prop | type | default |');
  lines.push('|------|------|---------|');
  for (const [k, v] of Object.entries(s.defaultProps)) {
    const doc = s.props[k] ? s.props[k].doc : '';
    const type = s.props[k] ? s.props[k].type : typeof v;
    lines.push(`| \`${k}\` | ${type} | \`${JSON.stringify(v)}\` | ${doc}`);
  }
  if (s.slots.length) {
    lines.push('');
    lines.push(`Slots the engine may overpaint: ${s.slots.map((sl) => `\`${sl.id}\` (${sl.note})`).join('; ')}.`);
  }
  lines.push('');
}
fs.writeFileSync(path.join(root, 'SHORTS.md'), lines.join('\n') + '\n');

console.log(`wrote shorts.json (${SHORTS.length} shorts), assets/cutscenes/shorts/shorts.json and SHORTS.md`);
